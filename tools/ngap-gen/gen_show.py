"""Emit show.bend: a normal form of every generated type's values, as text.

oracle.py prints the same normal form from pycrate's decoding of the capture
and compares. Numbers are decimal (an INTEGER's real value, an ENUMERATED's
index, `x` marking an extension), bit strings `b` plus the bits, octet and
character strings hex, records `{a,b,-}` (`-` an absent optional), choices
`i:value`, lists and IE containers `[,a,b]`, raw IEs `id/crit/hex`.
"""

HEADER = """import Base
import ../../bytes.bend as B
import ../../aper.bend as Ap
import ../frame.bend as Fr
import ./types.bend as G

# GENERATED by tools/ngap-gen/gen.py from TS 38.413 V17.15.0; do not edit.
# The textual normal form tools/ngap-gen/oracle.py compares with pycrate.

def Hex.nibble(b3: Bool, b2: Bool, b1: Bool, b0: Bool) -> String:
  match b3 b2 b1 b0:
    case False{} False{} False{} False{}:
      "0"
    case False{} False{} False{} True{}:
      "1"
    case False{} False{} True{} False{}:
      "2"
    case False{} False{} True{} True{}:
      "3"
    case False{} True{} False{} False{}:
      "4"
    case False{} True{} False{} True{}:
      "5"
    case False{} True{} True{} False{}:
      "6"
    case False{} True{} True{} True{}:
      "7"
    case True{} False{} False{} False{}:
      "8"
    case True{} False{} False{} True{}:
      "9"
    case True{} False{} True{} False{}:
      "a"
    case True{} False{} True{} True{}:
      "b"
    case True{} True{} False{} False{}:
      "c"
    case True{} True{} False{} True{}:
      "d"
    case True{} True{} True{} False{}:
      "e"
    case True{} True{} True{} True{}:
      "f"

def Hex.bits(bits: Ap.Bits()) -> String:
  match bits:
    case b7 <> b6 <> b5 <> b4 <> b3 <> b2 <> b1 <> b0 <> rest:
      Hex.nibble(b7, b6, b5, b4) ++ Hex.nibble(b3, b2, b1, b0) ++ Hex.bits(rest)
    case _:
      ""

def Hex.bytes(bs: B.Bytes()) -> String:
  Hex.bits(Ap.unpack(bs))

def Bits.show(bits: Ap.Bits()) -> String:
  match bits:
    case Nil{}:
      ""
    case b <> rest:
      match b:
        case False{}:
          "0" ++ Bits.show(rest)
        case True{}:
          "1" ++ Bits.show(rest)

def Dec(x: U32) -> String:
  Nat.show(U32.to_nat(x))

def Ie.show(ie: Fr.Ie) -> String:
  match ie:
    case Fr.Ie{id, crit, value}:
      Dec(id) ++ "/" ++ Dec(crit) ++ "/" ++ Hex.bytes(value)

def Ies.show(ies: List<&2, Fr.Ie>) -> String:
  match ies:
    case Nil{}:
      ""
    case ie <> more:
      "," ++ Ie.show(ie) ++ Ies.show(more)

def Exts.show(ies: List<&2, Fr.Ie>) -> String:
  "[" ++ Ies.show(ies) ++ "]"
"""

BITS = {"Bits", "ABits", "XBits", "BitStr", "XBitStr", "UBitStr"}
BYTES = {"Big", "Octets", "AOctets", "OctStr", "Open", "Str", "XStr", "UStr"}


class Show:
    def __init__(self, g):
        self.g = g
        self.lines = [HEADER]

    def out(self, text=""):
        self.lines.append(text)

    def data(self, name):
        if name == "EXTS":
            return "List<&2, Fr.Ie>"
        if name == "IE":
            return "Fr.Ie"
        return "G." + self.g.data(name)

    def call(self, name, v):
        if name == "EXTS":
            return f"Exts.show({v})"
        if name == "IE":
            return f"Ie.show({v})"
        return f"{self.g.types[name].bend}.show({v})"

    def show(self):
        done = set()

        def emit(name):
            if name in done:
                return
            done.add(name)
            t = self.g.types[name]
            for d in t.deps:
                emit(d)
            getattr(self, "emit_" + t.kind)(t)
            self.emit_rd(t)

        for name in self.g.order:
            if self.g.types[name].kind != "message":
                emit(name)
        for name in self.g.order:
            emit(name)
        self.emit_messages()
        return "\n".join(self.lines).rstrip() + "\n"

    def emit_rd(self, t):
        """The normal form of what a reader answered: `!` unless it consumed everything but padding."""
        b, d = t.bend, self.data(t.name)
        self.out(f"def {b}.show_end(+v: {d}, ok: Bool) -> String:")
        self.out("  match ok:")
        self.out("    case True{}:")
        self.out(f"      {b}.show(v)")
        self.out("    case False{}:")
        self.out('      "!"')
        self.out()
        self.out(f"def {b}.show_rd(r: Ap.Rd({d})) -> String:")
        self.out("  match r:")
        self.out("    case Fail{e}:")
        self.out('      "!"')
        self.out("    case Done{(v, c)}:")
        self.out("      match c:")
        self.out("        case Ap.Cur{rem, bits}:")
        self.out(f"          {b}.show_end(v, Ap.Tail.zero(bits))")
        self.out()

    def emit_alias(self, t):
        b, d, p = t.bend, self.data(t.name), t.prim
        self.out(f"def {b}.show(v: {d}) -> String:")
        if p in ("Int", "AInt"):
            self.out(f"  Dec(U32.add({t.lb}, v))")
        elif p == "XInt":
            self.out("  match v:")
            self.out("    case Ap.IRoot{x}:")
            self.out(f"      Dec(U32.add({t.lb}, x))")
            self.out("    case Ap.IExt{bs}:")
            self.out('      "x" ++ Hex.bytes(bs)')
        elif p == "XBig":
            self.out("  match v:")
            self.out("    case Ap.BRoot{bs}:")
            self.out("      Hex.bytes(bs)")
            self.out("    case Ap.BExt{bs}:")
            self.out('      "x" ++ Hex.bytes(bs)')
        elif p == "Enum":
            self.out("  match v:")
            self.out("    case Ap.Root{i}:")
            self.out("      Dec(i)")
            self.out("    case Ap.Ext{i}:")
            self.out('      "x" ++ Dec(i)')
        elif p in BITS:
            self.out('  "b" ++ Bits.show(v)')
        elif p in BYTES:
            self.out("  Hex.bytes(v)")
        else:
            raise ValueError(p)
        self.out()

    def emit_record(self, t):
        b, fields = t.bend, t.fields
        for fn, ft, o in fields:
            if o:
                self.out(f"def {b}.m_{fn}(m: Maybe<&2, {self.data(ft)}>) -> String:")
                self.out("  match m:")
                self.out("    case None{}:")
                self.out('      "-"')
                self.out("    case Some{v}:")
                self.out(f"      {self.call(ft, 'v')}")
                self.out()
        self.out(f"def {b}.show(x: G.{b}) -> String:")
        self.out("  match x:")
        self.out("    case G." + b + "{" + ", ".join(fn for fn, _, _ in fields) + "}:")
        parts = [f"{b}.m_{fn}({fn})" if o else self.call(ft, fn) for fn, ft, o in fields]
        self.out('      "{" ++ ' + ' ++ "," ++ '.join(parts) + ' ++ "}"')
        self.out()

    def emit_choice(self, t):
        b = t.bend
        self.out(f"def {b}.show(x: G.{b}) -> String:")
        self.out("  match x:")
        for j, (an, at) in enumerate(t.alts):
            self.out(f"    case G.{b}_{an}{{v}}:")
            self.out(f'      "{j}:" ++ {self.call(at, "v")}')
        self.out()

    def emit_list(self, t):
        b, item = t.bend, t.item
        d = self.data(item)
        self.out(f"def {b}.show_items(xs: List<&2, {d}>) -> String:")
        self.out("  match xs:")
        self.out("    case Nil{}:")
        self.out('      ""')
        self.out("    case x <> more:")
        self.out(f'      "," ++ {self.call(item, "x")} ++ {b}.show_items(more)')
        self.out()
        self.out(f"def {b}.show(xs: List<&2, {d}>) -> String:")
        self.out(f'  "[" ++ {b}.show_items(xs) ++ "]"')
        self.out()

    def emit_message(self, t):
        b = t.bend
        rows = self.g.view_rows(t.name)
        self.out(f"def {b}.show_ie(id: Nat, +value: B.Bytes()) -> String:")
        self.out("  match id:")
        for iid, _, tn, _ in rows:
            tb = self.g.types[tn].bend
            self.out(f"    case {iid}n:")
            self.out(f"      {tb}.show_rd(G.{tb}.read(Ap.Cur{{0n, Ap.unpack(value)}}))")
        self.out("    case _:")
        self.out("      Hex.bytes(value)")
        self.out()
        self.out(f"def {b}.show_ies(ies: List<&2, Fr.Ie>) -> String:")
        self.out("  match ies:")
        self.out("    case Nil{}:")
        self.out('      ""')
        self.out("    case ie <> more:")
        self.out("      match ie:")
        self.out("        case Fr.Ie{+id, crit, value}:")
        self.out(f'          "," ++ Dec(id) ++ "/" ++ Dec(crit) ++ "/" ++ {b}.show_ie(U32.to_nat(id), value) ++ {b}.show_ies(more)')
        self.out()
        self.out(f"def {b}.show(ies: G.{b}()) -> String:")
        self.out(f'  "[" ++ {b}.show_ies(ies) ++ "]"')
        self.out()

    def emit_messages(self):
        self.out("# The normal form of a named message's value octets (the open type after the PDU header).")
        self.out("def Message.show(msg: String, +value: B.Bytes()) -> Maybe<&2, String>:")
        self.out("  match msg:")
        for msg in sorted(self.g.messages):
            b = self.g.types[msg].bend
            self.out(f'    case "{msg}":')
            self.out(f"      Some{{{b}.show_rd(G.{b}.read(Ap.Cur{{0n, Ap.unpack(value)}}))}}")
        self.out("    case _:")
        self.out("      None{}")
