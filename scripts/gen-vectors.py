#!/usr/bin/env python3
"""Turns every test-vectors/**/*.json into a Bend module under kernel/tests/vectors/.

test-vectors/spec/fips180-4.json becomes kernel/tests/vectors/spec-fips180-4.bend,
whose `data()` is the document as a `Vec` (kernel/tests/lib/vec.bend).
`--check` fails if the committed modules differ from what would be generated.
Run with `python3 -I`.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "test-vectors"
OUT = ROOT / "kernel/tests/vectors"
NAT_MAX = 4294967295


def bend_string(s):
    return json.dumps(s, ensure_ascii=False)


def emit(value, indent):
    pad = "  " * indent
    if isinstance(value, bool):
        return "V.VBool{%s}" % ("True{}" if value else "False{}")
    if value is None:
        return "V.VNull{}"
    if isinstance(value, int) and 0 <= value <= NAT_MAX:
        return "V.VNat{%dn}" % value
    if isinstance(value, (int, float)):
        return "V.VText{%s}" % bend_string(repr(value))
    if isinstance(value, str):
        return "V.VText{%s}" % bend_string(value)
    if isinstance(value, list):
        if not value:
            return "V.VList{[]}"
        items = (",\n" + pad + "  ").join(emit(v, indent + 1) for v in value)
        return "V.VList{[\n%s  %s\n%s]}" % (pad, items, pad)
    if isinstance(value, dict):
        if not value:
            return "V.VObj{[]}"
        fields = (",\n" + pad + "  ").join(
            "V.Field{%s, %s}" % (bend_string(k), emit(v, indent + 1)) for k, v in value.items()
        )
        return "V.VObj{[\n%s  %s\n%s]}" % (pad, fields, pad)
    raise TypeError(type(value))


def module(path):
    rel = path.relative_to(SRC)
    name = "-".join(rel.with_suffix("").parts)
    data = json.loads(path.read_text())
    text = (
        "import Base\n"
        "import ../lib/vec.bend as V\n\n"
        f"# Generated by scripts/gen-vectors.py from test-vectors/{rel}. Do not edit.\n"
        "def data() -> V.Vec:\n"
        f"  {emit(data, 1)}\n"
    )
    return OUT / f"{name}.bend", text


def main():
    check = "--check" in sys.argv[1:]
    expected = dict(module(p) for p in sorted(SRC.rglob("*.json")))
    existing = set(OUT.glob("*.bend")) if OUT.exists() else set()
    stale = existing - set(expected)
    changed = [p for p, text in expected.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        for p in changed:
            print(f"differs: {p.relative_to(ROOT)}")
        print(f"{len(expected)} modules, {len(changed)} differ, {len(stale)} stale")
        sys.exit(1 if changed or stale else 0)
    OUT.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.unlink()
    for p in changed:
        p.write_text(expected[p])
    print(f"{len(expected)} modules, {len(changed)} written, {len(stale)} removed")


if __name__ == "__main__":
    main()
